#!/usr/bin/env node
/** Original synthetic cough cues around existing, attributed German speech. */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRandom, encodeMonoPcmWav, worldAudioRate } from './world-audio-synthesis.mjs';

export const tapeExerciseIds = ['b1-witness-exercise-3', 'b1-witness-exercise-7', 'b1-witness-exercise-6'];
const rootDirectory = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const cueSeed = 12676103;

/** Seeded foley, deliberately labelled synthetic rather than a human recording. */
export function synthesizeTapeCough(rate = worldAudioRate, seed = cueSeed) {
  const samples = new Float32Array(Math.round(rate * .38)), random = createRandom(seed);
  let low = 0, band = 0;
  for (let i = 0; i < samples.length; i++) {
    const t = i / rate, noise = random() * 2 - 1;
    low = low * .8 + noise * .2; band = band * .35 + (noise - low) * .65;
    const envelope = Math.exp(-Math.pow((t - .055) / .032, 2)) + .65 * Math.exp(-Math.pow((t - .135) / .043, 2)) + .35 * Math.exp(-Math.pow((t - .24) / .047, 2));
    const pulse = Math.sin(t * Math.PI * 2 * (125 - t * 75)) + .3 * Math.sin(t * Math.PI * 2 * 340);
    samples[i] = (.26 * band + .13 * pulse) * envelope * Math.min(1, t * 120) * Math.min(1, (.38 - t) * 80);
  }
  return samples;
}

export function composeTapeSamples(voice, rate = worldAudioRate) {
  if (!voice.length || !voice.every(Number.isFinite)) throw Error('A tape needs finite, non-empty decoded speech');
  const cough = synthesizeTapeCough(rate), gap = Math.round(rate * .3), prefix = cough.length + gap;
  const tail = prefix + voice.length + gap, samples = new Float32Array(tail + cough.length + gap);
  samples.set(cough); samples.set(voice, prefix); samples.set(cough, tail);
  return { samples, coughPositionsMs: [0, Math.round(tail * 1000 / rate)], speechStartsMs: Math.round(prefix * 1000 / rate), coughDurationMs: Math.round(cough.length * 1000 / rate) };
}

function ffmpeg(args, input) {
  const result = spawnSync(process.env.FFMPEG_PATH || 'ffmpeg', args, { input, maxBuffer: 16 * 1024 * 1024, timeout: 30000 });
  if (result.error || result.status !== 0) throw Error(result.error?.message || result.stderr.toString().trim());
  return result.stdout;
}

export async function prepareMiniGameTapes(root = rootDirectory) {
  const output = resolve(root, 'web/public/audio/minigames'); await mkdir(output, { recursive: true });
  const sourceCurriculum = JSON.parse(await readFile(resolve(root, 'server/curriculum.json'), 'utf8'));
  const clips = [];
  for (const exerciseId of tapeExerciseIds) {
    const exercise = sourceCurriculum.exercises.find(exercise => exercise.id === exerciseId && exercise.mode === 'production');
    if (!exercise) throw Error(`Missing authored witness production exercise: ${exerciseId}`);
    const source = `web/public/audio/${exerciseId}.ogg`;
    const decoded = ffmpeg(['-v', 'error', '-i', resolve(root, source), '-f', 'f32le', '-ar', String(worldAudioRate), '-ac', '1', 'pipe:1']);
    if (decoded.length % 4) throw Error(`Invalid decoded PCM: ${exerciseId}`);
    const voice = new Float32Array(decoded.length / 4);
    for (let i = 0; i < voice.length; i++) voice[i] = decoded.readFloatLE(i * 4);
    const tape = composeTapeSamples(voice), path = `/audio/minigames/loop-${exerciseId}.ogg`;
    ffmpeg(['-v', 'error', '-y', '-f', 'wav', '-i', 'pipe:0', '-c:a', 'libopus', '-b:a', '48k', resolve(root, `web/public${path}`)], encodeMonoPcmWav(tape.samples));
    const sourceSha256 = createHash('sha256').update(await readFile(resolve(root, source))).digest('hex');
    clips.push({ exerciseId, text: exercise.answer, path, coughPositionsMs: tape.coughPositionsMs, coughDurationMs: tape.coughDurationMs, speechStartsMs: tape.speechStartsMs, durationMs: Math.round(tape.samples.length * 1000 / worldAudioRate), source, sourceSha256 });
  }
  // Progression uses actual decoded speech duration, not a guessed waveform.
  clips.sort((a, b) => a.durationMs - b.durationMs);
  const manifest = {
    version: 1, sampleRate: worldAudioRate, clips,
    provenance: {
      script: 'scripts/prepare-minigame-tapes.mjs',
      speech: 'Existing project Opus clips generated by scripts/generate-audio.mjs using macOS Anna (de_DE), 145 words/minute.',
      cough: 'Original deterministic synthetic cough-like foley; no human performer or external samples.',
      coughSeed: cueSeed, repeatedCue: 'The same synthesized PCM cue is copied at both recorded marker positions.',
      encoding: 'Ogg Opus, libopus, 48 kbps, mono',
      waveform: 'No fabricated waveform data. The game reads the actual playing clip through Web Audio.',
    },
  };
  await writeFile(resolve(output, 'loop-manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
  await writeFile(resolve(root, 'web/src/minigames/loop-data.json'), `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`Prepared ${clips.length} witness tapes with repeated synthetic cough cues.`);
  return manifest;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await prepareMiniGameTapes();
