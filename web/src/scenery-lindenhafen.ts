// Silhouettes traced in the painting's native 1536 × 1024 coordinates. Only the
// narrow lamp shaft is copied between its head and its base: the surrounding
// street must stay transparent when somebody walks behind the lantern.
function lamp(id: string, x: number, top: number, baseY: number, width = 8): ScenerySpec {
  const neck = top + 29;
  return {
    id, baseY,
    outline: [
      [x,top],[x+2,top+8],[x+width,top+13],[x+width-1,top+17],
      [x+width-2,top+24],[x+3,neck],[x+1.5,neck+5],
      [x+1.5,baseY-12],[x+4,baseY-7],[x+5,baseY-2],[x+2,baseY],
      [x-5,baseY],[x-6,baseY-3],[x-3,baseY-10],[x-1.5,baseY-12],
      [x-1.5,neck+4],[x-3,neck],[x-width+2,top+24],
      [x-width+1,top+17],[x-width,top+13],[x-2,top+8],
    ],
    footprint: [[x-4,baseY-5],[x+4,baseY-5],[x+5,baseY-1],[x,baseY+2],[x-5,baseY-1]],
  };
}

