import type { ScenerySpec } from './scenery';

// Coordinates are traced against the 1536 × 1024 runtime paintings. Only the
// painted object is copied, so nearby paving remains transparent to actors.
// The sorting anchor is its ground contact, never the top of its silhouette.
function lamp(id: string, x: number, top: number, baseY: number, cap = 8): ScenerySpec {
  const lanternScale = Math.min(1, (baseY - top - 12) / 31);
  const level = (offset: number) => top + offset * lanternScale;
  return {
    id, baseY,
    outline: [
      [x, top], [x + 2, level(6)], [x + cap, level(11)],
      [x + cap - 2, level(14)], [x + cap - 3, level(26)],
      [x + 2, level(31)], [x + 2, baseY - 10],
      [x + 5, baseY - 6], [x + 5, baseY], [x - 5, baseY],
      [x - 5, baseY - 6], [x - 2, baseY - 10], [x - 2, level(31)],
      [x - cap + 3, level(26)], [x - cap + 2, level(14)],
      [x - cap, level(11)], [x - 2, level(6)],
    ],
    footprint: [[x - 4, baseY - 5], [x + 4, baseY - 5], [x + 4, baseY + 2], [x - 4, baseY + 2]],
  };
}

